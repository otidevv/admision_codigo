        private static void SeedCountries(AppDbContext context)
        {
            // Full ISO 3166-1 list in Spanish. Seed is additive: countries already
            // present (by Code) are skipped so existing FKs remain valid.
            var catalog = CountryCatalog();

            var existingCodes = context.Countries
                .Select(c => c.Code)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var missing = catalog
                .Where(c => !existingCodes.Contains(c.Code))
                .Select(c => new Country
                {
                    Id = Guid.NewGuid(),
                    Name = c.Name,
                    Code = c.Code,
                    CreatedBy = "System",
                    CreatedAt = DateTimeOffset.UtcNow
                })
                .ToList();

            if (missing.Count == 0)
            {
                Console.WriteLine("Countries table is complete. Nothing to seed.");
                return;
            }

            Console.WriteLine($"Seeding {missing.Count} missing countries...");
            context.Countries.AddRange(missing);
            context.SaveChanges();
            Console.WriteLine($"Seeded {missing.Count} countries. Total now: {existingCodes.Count + missing.Count}.");
        }

